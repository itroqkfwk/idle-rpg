export function getSkillPiecesRequired(skill: Skill): number {
  const baseReq = skill.rarity === 'mythic' ? 10 : skill.rarity === 'legendary' ? 5 : skill.rarity === 'epic' ? 4 : skill.rarity === 'rare' ? 3 : 2;
  const growthRate = skill.rarity === 'mythic' ? 8 : skill.rarity === 'legendary' ? 5 : skill.rarity === 'epic' ? 4 : skill.rarity === 'rare' ? 3 : 2;
  return baseReq + (skill.level - 1) * growthRate;
}

export function getSkillUpgradeGoldCost(skill: Skill): number {
  const baseCost = skill.rarity === 'mythic' ? 10000 : skill.rarity === 'legendary' ? 5000 : skill.rarity === 'epic' ? 2500 : skill.rarity === 'rare' ? 1000 : 400;
  return baseCost * skill.level;
}

export function calculateSkillOwnedStats(skill: Skill): {
  ownedAtk: number;
  ownedHp: number;
  ownedDef: number;
  ownedCritDmg: number;
} {
  if (!skill.owned) {
    return { ownedAtk: 0, ownedHp: 0, ownedDef: 0, ownedCritDmg: 0 };
  }
  const levelMult = 1 + (skill.level - 1) * 0.15;
  return {
    ownedAtk: Math.floor((skill.ownedAtk || 0) * levelMult),
    ownedHp: Math.floor((skill.ownedHp || 0) * levelMult),
    ownedDef: Math.floor((skill.ownedDef || 0) * levelMult),
    ownedCritDmg: Number(((skill.ownedCritDmg || 0) * levelMult).toFixed(1)),
  };
}

export function calculateTotalSkillOwnedBonus(skills: Skill[]): {
  ownedAtk: number;
  ownedHp: number;
  ownedDef: number;
  ownedCritDmg: number;
} {
  let totalAtk = 0;
  let totalHp = 0;
  let totalDef = 0;
  let totalCritDmg = 0;

  for (const skill of skills) {
    if (skill.owned) {
      const stats = calculateSkillOwnedStats(skill);
      totalAtk += stats.ownedAtk;
      totalHp += stats.ownedHp;
      totalDef += stats.ownedDef;
      totalCritDmg += stats.ownedCritDmg;
    }
  }

  return {
    ownedAtk: totalAtk,
    ownedHp: totalHp,
    ownedDef: totalDef,
    ownedCritDmg: Number(totalCritDmg.toFixed(1)),
  };
}

/**
 * Multi-vector skill power scoring (Boss vs Normal Wave AI selection)
 */
export function calculateSkillScoreVector(skill: Skill): SkillPowerScoreVector {
  if (skill.isAwakening) {
    return { totalScore: 999999, bossDamage: 99999, aoeDamage: 99999, survival: 5000, utility: 5000 };
  }
  const currentMult = skill.baseDamageMult + (skill.level - 1) * skill.damageMultPerLevel;
  const hits = skill.hits || 1;
  const totalMult = currentMult * hits;
  const cd = Math.max(skill.cooldown, 1);
  const baseDps = (totalMult / cd) * 100;

  const mechanics = skill.mechanics || [];
  const isBossPrior = skill.bossPriority || mechanics.includes('boss_slayer') || mechanics.includes('execute');
  const isAoe = mechanics.includes('aoe') || mechanics.includes('hazard') || mechanics.includes('chain');
  const isSurvival = mechanics.includes('shield') || mechanics.includes('lifesteal');
  const isUtility = mechanics.includes('stun') || mechanics.includes('freeze') || mechanics.includes('def_shred') || mechanics.includes('pull');

  const bossDamage = Math.round(baseDps * (isBossPrior ? 1.5 : 1.0) + (isBossPrior ? 40 : 0));
  const aoeDamage = Math.round(baseDps * (isAoe ? 1.4 : 0.8) + (isAoe ? 35 : 0));
  const survival = isSurvival ? 50 + skill.level * 3 : 10;
  const utility = isUtility ? 45 + skill.level * 2 : 10;

  const rarityBonus = skill.rarity === 'mythic' ? 60 : skill.rarity === 'legendary' ? 40 : skill.rarity === 'epic' ? 25 : skill.rarity === 'rare' ? 12 : 0;
  const totalScore = Math.round((bossDamage + aoeDamage) * 0.5 + survival + utility + rarityBonus + skill.level * 5);

  return {
    totalScore,
    bossDamage,
    aoeDamage,
    survival,
    utility,
  };
}

/**
 * Calculates Expected DPS / combat rating for a skill to drive Smart Auto-Equip,
 * dynamically balancing whether the player is fighting a Boss or clearing waves.
 */
export function calculateSkillPowerScore(skill: Skill, isBossStage: boolean = false): number {
  if (skill.isAwakening) return 999999;
  const vector = calculateSkillScoreVector(skill);

  if (isBossStage) {
    // Boss battle priorities: single target DPS, boss slayers, survival, armor shred
    return Math.round(vector.bossDamage * 1.5 + vector.survival * 1.2 + vector.utility * 1.1);
  } else {
    // Normal waves: AoE clearing, multi-hit, fast cooldowns
    return Math.round(vector.aoeDamage * 1.4 + vector.bossDamage * 0.9 + vector.utility * 1.0);
  }
}
